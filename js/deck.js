// deck.js — логика колоды. Здесь нет ни одного обращения к HTML-странице
// (document, window). Благодаря этому модуль можно подключить и в браузере,
// и в Node.js, где мы его тестируем.

// Подзаголовок, которым в толковании отмечен последний абзац.
// Вынесен в константу, чтобы строка не повторялась в разных местах кода.
export const ADVICE_HEADING = 'Наставление';

// Загружает колоду из JSON-файла и возвращает массив карт.
// fetchFn — функция загрузки. По умолчанию это встроенный fetch браузера,
// но в тестах вместо неё можно передать свою функцию и не обращаться к сети.
export async function loadDeck(url, fetchFn = fetch) {
  const response = await fetchFn(url);

  // fetch не выбрасывает ошибку при ответе 404 или 500, он просто
  // возвращает response.ok === false. Проверяем сами, иначе дальше
  // попытаемся разобрать страницу ошибки как JSON и получим непонятную ошибку.
  if (!response.ok) {
    throw new Error(`Не удалось загрузить колоду: ${response.status}`);
  }

  const deck = await response.json();

  // Если в файле окажется не массив или пустой массив, лучше узнать
  // об этом сразу при загрузке, а не позже при попытке вытянуть карту.
  if (!Array.isArray(deck) || deck.length === 0) {
    throw new Error('Колода пуста или имеет неверный формат');
  }

  return deck;
}

// Выбирает случайную карту из колоды.
// previousId — id карты, которая выпала в прошлый раз (или null, если это
// первая карта). Эта карта исключается из выбора, чтобы она не выпала
// два раза подряд.
// random — функция, возвращающая число от 0 (включительно) до 1 (не включая 1).
// По умолчанию это Math.random. Параметр нужен тестам: они могут передать
// функцию с заранее известным результатом.
export function pickRandomCard(deck, previousId = null, random = Math.random) {
  if (deck.length === 0) {
    throw new Error('Нельзя вытянуть карту из пустой колоды');
  }

  // Сначала убираем прошлую карту из списка кандидатов, а потом выбираем
  // среди оставшихся. Так выбор всегда занимает один шаг, и не нужен цикл
  // «тянуть заново, пока не выпадет другая».
  const candidates = deck.filter((card) => card.id !== previousId);

  // Если в колоде всего одна карта, после фильтра кандидатов не останется.
  // В этом случае допускаем повтор, ведь другой карты просто нет.
  const pool = candidates.length > 0 ? candidates : deck;

  // random() даёт дробное число от 0 до 1. Умножаем на количество карт
  // и отбрасываем дробную часть, получаем индекс от 0 до pool.length - 1.
  const index = Math.floor(random() * pool.length);
  return pool[index];
}

// Разбивает текст толкования на блоки для показа на экране.
// Возвращает массив объектов вида { type: 'paragraph' | 'heading', text }.
// Сама функция ничего не рисует. Она только описывает, что нужно показать,
// а app.js по этому описанию создаёт HTML-элементы.
export function splitText(text) {
  return text
    .split('\n')                         // абзацы в JSON разделены символом \n
    .map((line) => line.trim())          // убираем случайные пробелы по краям
    .filter((line) => line.length > 0)   // пустые строки не превращаем в пустые абзацы
    .map((line) => ({
      type: line === ADVICE_HEADING ? 'heading' : 'paragraph',
      text: line,
    }));
}
